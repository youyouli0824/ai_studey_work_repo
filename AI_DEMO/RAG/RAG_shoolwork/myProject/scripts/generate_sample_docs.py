sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from docx import Document as DocxDocument
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt


def add_document(path: Path, title: str, subtitle: str, content) -> None:
    """content 为 (样式, 文本) 元组列表，样式：title/sub/heading/para/line。"""
    doc = DocxDocument()

    h = doc.add_paragraph()
    h.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = h.add_run(title)
    run.bold = True
    run.font.size = Pt(18)

    s = doc.add_paragraph()
    s.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = s.add_run(subtitle)
    run.font.size = Pt(10)

    for style, text in content:
        if style == "heading":
            p = doc.add_paragraph()
            run = p.add_run(text)
            run.bold = True
            run.font.size = Pt(14)
        elif style == "sub":
            p = doc.add_paragraph()
            run = p.add_run(text)
            run.bold = True
        else:
            p = doc.add_paragraph(text)
            p.paragraph_format.first_line_indent = Pt(24)

    doc.save(str(path))
    print(f"已生成：{path.name}")


